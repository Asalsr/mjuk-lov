export type Lang = "sv" | "en" | "fa";

export const LANGS: Lang[] = ["sv", "en", "fa"];

/** Right-to-left locales (Persian). Drives `dir="rtl"` and the Persian font. */
export const RTL_LANGS: Lang[] = ["fa"];
export const isRtl = (lang: Lang): boolean => RTL_LANGS.includes(lang);

export function isLang(x: string): x is Lang {
  return x === "sv" || x === "en" || x === "fa";
}

